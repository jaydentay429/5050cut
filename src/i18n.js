function langIndex(code) {
  if (code === "zh-Hant") return 1;
  if (code === "en") return 2;
  return 0;
}

function detectLang() {
  try {
    const saved = localStorage.getItem(KEY);
    if (LANGS.includes(saved)) return saved;
  } catch {
    /* ignore */
  }
  try {
    const n = String(navigator.language || "").toLowerCase();
    if (n.includes("hans") || n.startsWith("zh-cn") || n.startsWith("zh-sg")) return "zh-Hans";
    if (n.startsWith("zh")) return "zh-Hant";
    if (n.startsWith("en")) return "en";
  } catch {
    /* ignore */
  }
  return "zh-Hans";
}

let lang = detectLang();

export function getLang() {
  return lang;
}

export function setLang(next) {
  if (!LANGS.includes(next)) return lang;
  lang = next;
  try {
    localStorage.setItem(KEY, lang);
  } catch {
    /* ignore */
  }
  applyDomLang();
  return lang;
}

export function cycleLang() {
  const i = LANGS.indexOf(lang);
  return setLang(LANGS[(i + 1) % LANGS.length]);
}

export function t(key, vars) {
  const pack = UI[lang] || UI["zh-Hans"];
  let text = pack[key] ?? UI["zh-Hans"][key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function typeLabel(id) {
  const row = ITEMS[id];
  if (!row) return id;
  return row[langIndex(lang)] || row[0] || id;
}

export function themeName(id) {
  return t(`theme_${id}`);
}

export function achieveTitle(id) {
  const row = ACH[id];
  if (!row) return "";
  return row[langIndex(lang)] || row[0] || "";
}

export function achieveHint(id) {
  const row = ACH_HINT[id];
  if (!row) return "";
  return row[langIndex(lang)] || row[0] || "";
}

export function titleIdFromStored(text) {
  const value = String(text || "");
  if (!value) return "";
  for (const [id, names] of Object.entries(ACH)) {
    if (names.includes(value)) return id;
  }
  return "";
}

export function langShort() {
  if (lang === "zh-Hant") return "繁";
  if (lang === "en") return "EN";
  return "简";
}

export function htmlLang() {
  if (lang === "zh-Hant") return "zh-Hant";
  if (lang === "en") return "en";
  return "zh-Hans";
}

export function applyDomLang() {
  try {
    // In-game copy follows `lang`. The document title and <html lang> stay
    // as served so crawlers see one stable page.
    document.documentElement.dataset.lang = lang;
    const bootTitle = document.getElementById("boot-load-title");
    if (bootTitle) bootTitle.textContent = t("title");
    const bootText = document.getElementById("boot-load-text");
    if (bootText && !bootText.dataset.lock) bootText.textContent = t("boot");
    const map = [
      ["[data-i18n='nickTitle']", "nickTitle"],
      ["[data-i18n='nickBody']", "nickBody"],
      ["[data-i18n='nickLabel']", "nickLabel"],
      ["[data-i18n='nickSave']", "nickSave"],
      ["[data-i18n='nickIdLabel']", "nickIdLabel"],
      ["[data-i18n='nickIdHint']", "nickIdHint"],
      ["[data-i18n='nickIdCopy']", "nickIdCopy"],
      ["[data-i18n='titleHead']", "titleHead"],
      ["[data-i18n='titleBody']", "titleBody"],
      ["[data-i18n='titleEmpty']", "titleEmpty"],
      ["[data-i18n='titleNone']", "titleNone"],
      ["[data-i18n='cancel']", "cancel"],
      ["[data-i18n='privacy']", "privacy"],
    ];
    for (const [sel, key] of map) {
      document.querySelectorAll(sel).forEach((el) => {
        el.textContent = t(key);
      });
    }
  } catch {
    /* ignore */
  }
}

